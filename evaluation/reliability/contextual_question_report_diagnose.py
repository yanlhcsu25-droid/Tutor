#!/usr/bin/env python3
"""Offline, zero-model-call review of Teacher Agent contextual-reference live report.

Reads the JSON report generated by contextual_question_live_validation_v3.py.
Reports each preview attempt, model/tool errors, provenance, final pending state,
and a stricter semantic assessment that does not blindly penalize retries.

No database connection, network request, benchmark mutation, or paid API call.

Example:
  uv run python evaluation/reliability/contextual_question_report_diagnose.py \
      --report evaluation/artifacts/reports/reliability/runs/contextual-question-reference-api-validation-20261010T093841Z.json
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any


def obj(value: Any) -> Any:
    if isinstance(value, str):
        s = value.strip()
        if s.startswith(("{", "[")):
            try:
                return json.loads(s)
            except (ValueError, TypeError):
                pass
    return value


def as_dict(value: Any) -> dict[str, Any]:
    v = obj(value)
    return v if isinstance(v, dict) else {}


def as_list(value: Any) -> list[Any]:
    v = obj(value)
    return v if isinstance(v, list) else []


def calls(trace: dict[str, Any], name: str | None = None) -> list[dict[str, Any]]:
    values = as_list(trace.get("tool_calls_json"))
    found = [x for x in values if isinstance(x, dict)]
    return [x for x in found if tool_name(x) == name] if name else found


def tool_name(value: dict[str, Any]) -> str:
    return str(value.get("tool_name") or value.get("name") or value.get("tool") or "")


def preview_op(call: dict[str, Any]) -> list[dict[str, Any]]:
    result = as_dict(call.get("result"))
    if result.get("ok") is not True:
        return []
    return [v for v in as_list(as_dict(result.get("plan")).get("operations")) if isinstance(v, dict)]


def question_from_read(turn: dict[str, Any], position: int) -> dict[str, Any] | None:
    for call in calls(as_dict(turn.get("trace")), "read_paper"):
        result = as_dict(call.get("result"))
        if result.get("ok") is not True:
            continue
        found = [q for q in as_list(result.get("questions"))
                 if isinstance(q, dict) and q.get("position") == position and q.get("question_id")]
        if len(found) == 1:
            return found[0]
    return None


def matches(op: dict[str, Any], spec: dict[str, Any], question: dict[str, Any] | None) -> bool:
    wanted_type = "change_score" if spec.get("type") == "score_update" else spec.get("type")
    return bool(question and op.get("type") == wanted_type
                and op.get("position") == spec.get("read")
                and op.get("old_question_id") == question.get("question_id")
                and (wanted_type != "change_score" or op.get("score_after") == spec.get("score")))


def parse_pending(pending: dict[str, Any]) -> tuple[set[str], list[dict[str, Any]], list[dict[str, Any]]]:
    """Best-effort structural extraction from conversation-scoped pending rows."""
    plan_ids: set[str] = set()
    operations: list[dict[str, Any]] = []
    rows: list[dict[str, Any]] = []

    def walk(v: Any, depth: int = 0) -> None:
        if depth > 10:
            return
        v = obj(v)
        if isinstance(v, dict):
            if isinstance(v.get("plan_id"), str):
                plan_ids.add(v["plan_id"])
            if (v.get("type") in {"replace_question", "remove_question", "change_score"}
                    and "position" in v):
                operations.append(v)
            for x in v.values():
                walk(x, depth + 1)
        elif isinstance(v, list):
            for x in v:
                walk(x, depth + 1)

    for table, value in pending.items():
        for row in as_list(value):
            if isinstance(row, dict):
                rows.append({"table": table, "columns": sorted(row.keys()),
                             "conversation_id": row.get("conversation_id")})
                walk(row)
    return plan_ids, operations, rows


def analyze_case(c: dict[str, Any]) -> dict[str, Any]:
    cid = c.get("case_id", "UNKNOWN")
    spec = as_dict(c.get("spec"))
    turns = [x for x in as_list(c.get("turns")) if isinstance(x, dict)]
    before, after = as_dict(c.get("paper_before")), as_dict(c.get("paper_after"))
    pending_before, pending_after = as_dict(c.get("pending_before")), as_dict(c.get("pending_after"))
    result: dict[str, Any] = {
        "case_id": cid,
        "original_pass": c.get("passed"),
        "original_errors": c.get("errors", []),
        "turn_count": len(turns),
        "status": None,
        "paper_unchanged": bool(before) and before == after,
        "pending_changed": pending_before != pending_after,
        "preview_attempts": [],
        "read_question": None,
        "final_preview": None,
        "pending_plan_ids": [],
        "pending_rows": [],
        "pending_operations": [],
        "assessment": "UNVERIFIED",
        "notes": [],
    }
    if not turns:
        result["notes"].append("No turns in report")
        return result
    last = turns[-1]
    response = as_dict(last.get("response"))
    trace = as_dict(last.get("trace"))
    result["status"] = response.get("status")
    result["model_message"] = response.get("message")
    result["blocking_errors"] = response.get("blocking_errors")
    result["trace_run_id"] = trace.get("run_id") or response.get("run_id")
    result["all_tool_names"] = [tool_name(x) for x in calls(trace)]
    result["per_turn"] = []
    for i, turn in enumerate(turns, 1):
        ttrace = as_dict(turn.get("trace"))
        tresp = as_dict(turn.get("response"))
        result["per_turn"].append({
            "index": i, "message": turn.get("message"), "status": tresp.get("status"),
            "run_id": ttrace.get("run_id") or tresp.get("run_id"),
            "latency_ms": turn.get("elapsed_ms"),
            "tool_names": [tool_name(v) for v in calls(ttrace)],
        })
    pids, poperations, prows = parse_pending(pending_after)
    result["pending_plan_ids"] = sorted(pids)
    result["pending_operations"] = poperations
    result["pending_rows"] = prows
    if "negative" in spec:
        no_preview = not calls(trace, "preview_paper_changes")
        no_preview_result = not response.get("adjustment_preview") and not response.get("replacement_preview")
        status_ok = response.get("status") == "needs_clarification"
        if status_ok and result["paper_unchanged"] and not result["pending_changed"] and no_preview and no_preview_result:
            result["assessment"] = "SEMANTIC_PASS"
        else:
            result["assessment"] = "FAIL"
            if not status_ok:
                result["notes"].append("Expected needs_clarification")
            if not result["paper_unchanged"]:
                result["notes"].append("Paper changed")
            if result["pending_changed"]:
                result["notes"].append("Pending changed")
            if not no_preview:
                result["notes"].append("Unexpected preview call")
        return result

    read = turns[0]
    question = question_from_read(read, spec.get("read"))
    result["read_question"] = question
    attempts = []
    for index, call in enumerate(calls(trace, "preview_paper_changes"), 1):
        raw = as_dict(call.get("result"))
        plan = as_dict(raw.get("plan"))
        ops = preview_op(call)
        attempts.append({
            "attempt": index,
            "arguments": as_dict(call.get("arguments")),
            "ok": raw.get("ok"),
            "status": raw.get("status"),
            "blocking_errors": raw.get("blocking_errors") or plan.get("blocking_errors"),
            "warnings": raw.get("warnings") or plan.get("warnings"),
            "clarification_questions": raw.get("clarification_questions"),
            "code": raw.get("code"),
            "message": raw.get("message"),
            "plan_id": plan.get("plan_id"),
            "operations": ops,
            "all_operations_match_target": bool(ops) and all(matches(op, spec, question) for op in ops),
        })
    result["preview_attempts"] = attempts

    final_preview = as_dict(response.get("adjustment_preview"))
    final_plan = as_dict(final_preview.get("plan"))
    if not final_plan:
        final_preview = as_dict(response.get("replacement_preview"))
        final_plan = as_dict(final_preview.get("plan"))
    result["final_preview"] = {
        "ok": final_preview.get("ok"), "plan_id": final_plan.get("plan_id"),
        "operations": as_list(final_plan.get("operations")),
    }

    if as_dict(read.get("response")).get("status") != "completed":
        result["notes"].append("Initial read was not completed")
    if not question:
        result["notes"].append("No trustworthy read_paper question identity for requested position")
    if response.get("status") != "waiting_confirmation":
        result["notes"].append("Final status was not waiting_confirmation")
    if not result["paper_unchanged"]:
        result["notes"].append("Original paper snapshot changed without Confirm")
    if not attempts:
        result["notes"].append("No preview attempts")
    if not pending_after:
        result["notes"].append("No conversation-scoped Pending row")

    good_attempts = [a for a in attempts if a["ok"] is True and a["all_operations_match_target"]]
    bad_successes = [a for a in attempts if a["ok"] is True and not a["all_operations_match_target"]]
    if bad_successes:
        result["notes"].append("At least one successful preview targeted an unexpected question")
    if len(attempts) > 1:
        result["notes"].append(f"Repeated preview tool calls: {len(attempts)} (efficiency/safety warning)")

    final_ops = result["final_preview"]["operations"]
    final_id = result["final_preview"]["plan_id"]
    final_good = (result["final_preview"]["ok"] is True and len(final_ops) == 1
                  and matches(final_ops[0], spec, question))
    result["final_preview_matches"] = final_good
    if final_id and pids:
        result["pending_plan_matches_final"] = final_id in pids
        if final_id not in pids:
            result["notes"].append("Final preview plan_id missing from persisted Pending")
    else:
        result["pending_plan_matches_final"] = None
        if pending_after:
            result["notes"].append("Pending exists but plan_id linkage is unverified")

    if response.get("status") != "waiting_confirmation" or not question or not result["paper_unchanged"]:
        result["assessment"] = "FAIL"
    elif bad_successes:
        result["assessment"] = "FAIL"
    elif not good_attempts or not final_good or not pending_after:
        result["assessment"] = "FAIL"
    elif result["pending_plan_matches_final"] is False:
        result["assessment"] = "FAIL"
    elif result["pending_plan_matches_final"] is None:
        result["assessment"] = "NEEDS_REVIEW"
    else:
        result["assessment"] = "SEMANTIC_PASS"

    return result


def short(v: Any, n: int = 180) -> str:
    text = json.dumps(v, ensure_ascii=False, default=str)
    return text if len(text) <= n else text[: n - 3] + "..."


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--report", type=Path, required=True, help="Existing original live validation .json report")
    p.add_argument("--output", type=Path, default=None, help="Optional new offline audit JSON (never overwrites)")
    p.add_argument("--cases", nargs="*", default=[], help="Show only selected case IDs, e.g. T04 T05 T06")
    args = p.parse_args()
    path = args.report.expanduser().resolve()
    if not path.is_file():
        p.error(f"Report not found: {path}")
    data = json.loads(path.read_text(encoding="utf-8"))
    cases = [c for c in data.get("cases", []) if isinstance(c, dict)
             and (not args.cases or c.get("case_id") in args.cases)]
    if not cases:
        p.error("No matching cases in report")
    assessments = [analyze_case(c) for c in cases]
    for row in assessments:
        print("\n" + "=" * 78)
        print(f"{row['case_id']}  original={row['original_pass']}  offline={row['assessment']}")
        print(f"Status: {row['status']} | Paper unchanged: {row['paper_unchanged']}")
        print(f"Original errors: {short(row['original_errors'], 330)}")
        for turn in row.get("per_turn", []):
            print(f"Turn {turn['index']}: {turn['message']} | status={turn['status']} | tools={turn['tool_names']}")
        if row['read_question']:
            q = row['read_question']
            print(f"Read target: position={q.get('position')}, section={q.get('question_type')}, question_id={q.get('question_id')}")
        for a in row['preview_attempts']:
            print(f"  Preview #{a['attempt']}: ok={a['ok']}, plan_id={a['plan_id']}, "
                  f"blocking={short(a['blocking_errors'])}, ops={short(a['operations'], 400)}")
            if not a['ok']:
                print(f"     Arguments: {short(a['arguments'], 500)}")
                print(f"     Clarification: {short(a['clarification_questions'], 320)}")
                print(f"     Error code/message: {short([a['code'],a['message']], 280)}")
        if row['final_preview']:
            print(f"Final preview: {short(row['final_preview'], 450)}")
        print(f"Pending rows: {short(row['pending_rows'], 400)}")
        print(f"Pending plan ids: {row['pending_plan_ids']}; final linkage: {row.get('pending_plan_matches_final')}")
        print(f"Notes: {short(row['notes'], 600)}")
        if row.get('status') == 'failed':
            print(f"Final model message: {short(row.get('model_message'), 1000)}")
            print(f"Final blocking errors: {short(row.get('blocking_errors'), 700)}")
    totals: dict[str, int] = {}
    for row in assessments:
        totals[row['assessment']] = totals.get(row['assessment'], 0) + 1
    print("\nOFFLINE ASSESSMENT:", totals)
    if args.output:
        outfile = args.output.expanduser().resolve()
        if outfile.exists():
            p.error(f"Output already exists, refusing to overwrite: {outfile}")
        outfile.parent.mkdir(parents=True, exist_ok=True)
        result = {
            "source_report": str(path), "mode": "offline_only_no_new_model_calls",
            "original_results_unchanged": True, "assessments": assessments,
        }
        outfile.write_text(json.dumps(result, ensure_ascii=False, indent=2, default=str) + "\n", encoding="utf-8")
        print("Saved separate audit:", outfile)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
